// v1alpha1 is the storage version. v1beta1 is the conversion hub.
//
// The mechanical field-by-field conversion is generated by conversion-gen into
// zz_generated.conversion.go (regenerate with `make generate`). Fields that
// conversion-gen cannot handle are converted by the hand-written
// Convert_* functions in this file.
//
// Following the pattern used by cluster-api-provider-metal3, cluster-api and
// cluster-api-provider-openstack, ConvertTo/ConvertFrom additionally use the
// conversion-data annotation (MarshalData/UnmarshalData, defined locally in
// conversion_data.go) to make the round-trip lossless.
//
// The annotation is used to store the information of the original object that
// cannot be represented in the other version, so that it is preserved. Only
// the required fields are stored, not the whole object, since annotations
// count towards the object size limit.
//

// --- BareMetalHost ---

// ConvertTo converts this BareMetalHost (v1alpha1) to the Hub version (v1beta1).
func (src *BareMetalHost) ConvertTo(dstRaw conversion.Hub) error {
	dst := dstRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1alpha1_BareMetalHost_To_v1beta1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}

	// Hardware profiles do not exist in v1beta1, which behaves as if the
	// "empty" profile was used. A profile only ever contributed root device
	// hints, so resolve them here: without this, a host that relies on the
	// hints implied by its profile would appear to have none at all when read
	// through v1beta1.
	//
	// Explicit hints always win, and only an explicitly known profile is
	// resolved. An unregistered host has no profile assigned yet (the name is
	// picked by the controller during registration), and guessing it here
	// would mean duplicating that heuristic in the API.
	hintsFromProfile := false
	if dst.Spec.RootDeviceHints == nil {
		if hints, ok := HardwareProfileRootDeviceHints(src.hardwareProfileName()); ok && hints != (RootDeviceHints{}) {
			converted := &metal3apiv1beta1.RootDeviceHints{}
			if err := Convert_v1alpha1_RootDeviceHints_To_v1beta1_RootDeviceHints(&hints, converted, nil); err != nil {
				return err
			}
			dst.Spec.RootDeviceHints = converted
			hintsFromProfile = true
		}
	}

	// The generated conversion shares the ObjectMeta maps between src and
	// dst. Copy the annotations so that the conversion data is not added to
	// src as well.
	dst.SetAnnotations(maps.Clone(src.GetAnnotations()))

	// Store only the v1alpha1 information that v1beta1 cannot represent and
	// that ConvertFrom cannot reconstruct, instead of the whole object: the
	// annotation counts towards the object size limit.
	data := bareMetalHostConversionData{
		HardwareProfile: newHardwareProfileConversionData(src, hintsFromProfile),
	}
	if data.isEmpty() {
		return nil
	}
	return marshalConversionData(data, dst)
}

// ConvertFrom converts the Hub version (v1beta1) to this BareMetalHost (v1alpha1).
func (dst *BareMetalHost) ConvertFrom(srcRaw conversion.Hub) error {
	src := srcRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1beta1_BareMetalHost_To_v1alpha1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}

	// UnmarshalData also removes the conversion-data annotation, so it does
	// not leak into the v1alpha1 object. Avoid manipulating the input data,
	// so copy the annotations first.
	restored := bareMetalHostConversionData{}
	dst.SetAnnotations(maps.Clone(src.GetAnnotations()))
	if _, err := UnmarshalData(dst, &restored); err != nil {
		return err
	}

	if profile := restored.HardwareProfile; profile != nil {
		dst.Spec.HardwareProfile = profile.Name
		dst.Status.HardwareProfile = profile.StatusName

		// Undo the root device hints that ConvertTo resolved from the profile,
		// but only while they still match the profile: anything else means the
		// hints were changed through v1beta1 and must be kept.
		if profile.RootDeviceHints && dst.Spec.RootDeviceHints != nil {
			if hints, ok := HardwareProfileRootDeviceHints(dst.hardwareProfileName()); ok &&
				*dst.Spec.RootDeviceHints == hints {
				dst.Spec.RootDeviceHints = nil
			}
		}
	}

	return nil
}

// bareMetalHostConversionData holds the parts of a v1alpha1 BareMetalHost that
// cannot be represented in v1beta1. It is stored in the conversion-data
// annotation of the v1beta1 object, so that a v1alpha1 -> v1beta1 -> v1alpha1
// round-trip is lossless.
type bareMetalHostConversionData struct {
	HardwareProfile *hardwareProfileConversionData `json:"hardwareProfile,omitempty"`
}

// isEmpty reports whether there is nothing to store.
func (d *bareMetalHostConversionData) isEmpty() bool {
	return d.HardwareProfile == nil
}

// hardwareProfileConversionData records the hardware profile of a v1alpha1
// BareMetalHost. Profiles do not exist in v1beta1, so neither the name nor its
// effect on the root device hints can be reconstructed from the hub object.
type hardwareProfileConversionData struct {
	// Name is Spec.HardwareProfile, the profile the user asked for.
	Name string `json:"name,omitempty"`

	// StatusName is Status.HardwareProfile, the profile the controller
	// assigned.
	StatusName string `json:"statusName,omitempty"`

	// RootDeviceHints is true if Spec.RootDeviceHints was unset and was filled
	// in from the profile by ConvertTo, so that ConvertFrom knows it may unset
	// them again.
	RootDeviceHints bool `json:"rootDeviceHints,omitempty"`
}

// newHardwareProfileConversionData returns the conversion data for the profile
// of host, or nil if there is nothing ConvertFrom would need.
func newHardwareProfileConversionData(host *BareMetalHost, hintsFromProfile bool) *hardwareProfileConversionData {
	data := hardwareProfileConversionData{
		Name:            host.Spec.HardwareProfile,
		StatusName:      host.Status.HardwareProfile,
		RootDeviceHints: hintsFromProfile,
	}
	if data == (hardwareProfileConversionData{}) {
		return nil
	}
	return &data
}

// hardwareProfileName returns the hardware profile the host is known to use.
// The status takes precedence because it records the profile the controller
// actually assigned, while the spec only holds the user's request.
func (host *BareMetalHost) hardwareProfileName() string {
	if host.Status.HardwareProfile != "" {
		return host.Status.HardwareProfile
	}
	return host.Spec.HardwareProfile
}

