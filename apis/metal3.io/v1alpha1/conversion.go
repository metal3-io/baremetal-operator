// v1alpha1 is the storage version. v1beta1 is the conversion hub.
//
// The mechanical field-by-field conversion is generated by conversion-gen into
// zz_generated.conversion.go (regenerate with `make generate`). Fields that
// conversion-gen cannot handle are converted by the hand-written
// Convert_* functions in this file.
//
// Following the pattern used by cluster-api-provider-metal3, cluster-api and
// cluster-api-provider-openstack, ConvertTo/ConvertFrom additionally use the
// conversion-data annotation (MarshalData/UnmarshalData, defined locally in
// conversion_data.go) to make the round-trip lossless.
//
// The annotation is used to store the information of the original object that
// cannot be represented in the other version, so that it is preserved. Only
// the required fields are stored, not the whole object, since annotations
// count towards the object size limit.
//

// --- BareMetalHost ---

// ConvertTo converts this BareMetalHost (v1alpha1) to the Hub version (v1beta1).
func (src *BareMetalHost) ConvertTo(dstRaw conversion.Hub) error {
	dst := dstRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1alpha1_BareMetalHost_To_v1beta1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}

	// v1beta1 does not allow cross-namespace Secret references
	validateNamespace := func(ref *corev1.SecretReference, fieldName string) error {
		if ref != nil && ref.Namespace != "" && ref.Namespace != src.Namespace {
			return field.Forbidden(
				field.NewPath("spec", fieldName, "namespace"),
				"cross-namespace Secret references are not allowed in v1beta1",
			)
		}
		return nil
	}
	if err := validateNamespace(src.Spec.UserData, "userData"); err != nil {
		return err
	}
	if err := validateNamespace(src.Spec.NetworkData, "networkData"); err != nil {
		return err
	}
	if err := validateNamespace(src.Spec.MetaData, "metaData"); err != nil {
		return err
	}

	// The generated conversion shares the ObjectMeta maps between src and
	// dst. Copy the annotations so that the conversion data is not added to
	// src as well.
	dst.SetAnnotations(maps.Clone(src.GetAnnotations()))

	// Store only the v1alpha1 information that v1beta1 cannot represent and
	// that ConvertFrom cannot reconstruct, instead of the whole object: the
	// annotation counts towards the object size limit.
	data := bareMetalHostConversionData{
		UserData:    newSecretReferenceConversionData(src.Spec.UserData),
		NetworkData: newSecretReferenceConversionData(src.Spec.NetworkData),
		MetaData:    newSecretReferenceConversionData(src.Spec.MetaData),
	}
	if data.isEmpty() {
		return nil
	}
	return marshalConversionData(data, dst)
}

// ConvertFrom converts the Hub version (v1beta1) to this BareMetalHost (v1alpha1).
func (dst *BareMetalHost) ConvertFrom(srcRaw conversion.Hub) error {
	src := srcRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1beta1_BareMetalHost_To_v1alpha1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}

	// UnmarshalData also removes the conversion-data annotation, so it does
	// not leak into the v1alpha1 object. Avoid manipulating the input data,
	// so copy the annotations first.
	restored := bareMetalHostConversionData{}
	dst.SetAnnotations(maps.Clone(src.GetAnnotations()))
	if _, err := UnmarshalData(dst, &restored); err != nil {
		return err
	}

	dst.Spec.UserData = restoreSecretReference(
		src.Spec.UserDataName, restored.UserData, src.Namespace)
	dst.Spec.NetworkData = restoreSecretReference(
		src.Spec.NetworkDataName, restored.NetworkData, src.Namespace)
	dst.Spec.MetaData = restoreSecretReference(
		src.Spec.MetaDataName, restored.MetaData, src.Namespace)

	return nil
}

// bareMetalHostConversionData holds the parts of a v1alpha1 BareMetalHost that
// cannot be represented in v1beta1. It is stored in the conversion-data
// annotation of the v1beta1 object, so that a v1alpha1 -> v1beta1 -> v1alpha1
// round-trip is lossless.
//
// Information about a Secret reference is only stored when the reference
// cannot be reconstructed from the v1beta1 Secret name and the namespace of
// the BareMetalHost (see newSecretReferenceConversionData).
type bareMetalHostConversionData struct {
	UserData    *secretReferenceConversionData `json:"userData,omitempty"`
	NetworkData *secretReferenceConversionData `json:"networkData,omitempty"`
	MetaData    *secretReferenceConversionData `json:"metaData,omitempty"`
}

// isEmpty reports whether there is nothing to store.
func (d *bareMetalHostConversionData) isEmpty() bool {
	return d.UserData == nil && d.NetworkData == nil && d.MetaData == nil
}

// secretReferenceConversionData records what the v1beta1 Secret name does not
// capture about a v1alpha1 Secret reference. The name itself is stored in
// v1beta1, and cross-namespace references are rejected by ConvertTo, so the
// namespace is either empty or the namespace of the BareMetalHost.
type secretReferenceConversionData struct {
	// EmptyName is true if the reference was set but had an empty name.
	// Without it, an empty v1beta1 Secret name means that the reference was
	// not set at all (nil).
	EmptyName bool `json:"emptyName,omitempty"`

	// EmptyNamespace is true if the reference had an empty namespace.
	// Without it, the namespace of the BareMetalHost is used.
	EmptyNamespace bool `json:"emptyNamespace,omitempty"`
}

// newSecretReferenceConversionData returns the conversion data for ref, or
// nil if ConvertFrom can reconstruct ref without it. ConvertFrom converts an
// empty v1beta1 Secret name to nil, and a non-empty name to a reference in the
// namespace of the BareMetalHost.
func newSecretReferenceConversionData(ref *corev1.SecretReference) *secretReferenceConversionData {
	if ref == nil {
		return nil
	}
	data := secretReferenceConversionData{
		EmptyName:      ref.Name == "",
		EmptyNamespace: ref.Namespace == "",
	}
	if !data.EmptyName && !data.EmptyNamespace {
		return nil
	}
	return &data
}

// Convert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec converts
// the BareMetalHostSpec from v1alpha1 to v1beta1.
//
// The userData, networkData and metaData Secret references are replaced by
// their names in v1beta1. The namespace is dropped since v1beta1 always uses
// the namespace of the BareMetalHost (cross-namespace references are already
// rejected for v1alpha1).
func Convert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec(in *BareMetalHostSpec, out *metal3apiv1beta1.BareMetalHostSpec, s apimachineryconversion.Scope) error {
	if err := autoConvert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec(in, out, s); err != nil {
		return err
	}

	out.UserDataName = secretReferenceName(in.UserData)
	out.NetworkDataName = secretReferenceName(in.NetworkData)
	out.MetaDataName = secretReferenceName(in.MetaData)

	return nil
}

// Convert_v1beta1_BareMetalHostSpec_To_v1alpha1_BareMetalHostSpec converts
// the BareMetalHostSpec from v1beta1 to v1alpha1.
//
// The userDataName, networkDataName and metaDataName fields are converted to
// Secret references with only the name set. The spec does not know the
// namespace of the BareMetalHost, so BareMetalHost.ConvertFrom fills it in.
func Convert_v1beta1_BareMetalHostSpec_To_v1alpha1_BareMetalHostSpec(in *metal3apiv1beta1.BareMetalHostSpec, out *BareMetalHostSpec, s apimachineryconversion.Scope) error {
	if err := autoConvert_v1beta1_BareMetalHostSpec_To_v1alpha1_BareMetalHostSpec(in, out, s); err != nil {
		return err
	}

	out.UserData = secretReferenceFromName(in.UserDataName, "")
	out.NetworkData = secretReferenceFromName(in.NetworkDataName, "")
	out.MetaData = secretReferenceFromName(in.MetaDataName, "")

	return nil
}

// secretReferenceName returns the name of the Secret reference, or an empty
// string if the reference is not set.
func secretReferenceName(ref *corev1.SecretReference) string {
	if ref == nil {
		return ""
	}
	return ref.Name
}

// secretReferenceFromName returns a Secret reference with the given name and
// namespace, or nil if the name is empty.
func secretReferenceFromName(name, namespace string) *corev1.SecretReference {
	if name == "" {
		return nil
	}
	return &corev1.SecretReference{Name: name, Namespace: namespace}
}

// restoreSecretReference builds the v1alpha1 Secret reference for a v1beta1
// Secret name, using the stored conversion data if there is any.
//
// An empty name gives nil, unless the reference was set with an empty name.
// Otherwise the reference points to the Secret in the namespace of the
// BareMetalHost, unless the namespace was empty. If the name was changed
// through v1beta1, the stored flags still apply; an empty namespace means the
// namespace of the BareMetalHost, so this does not change the Secret that is
// referenced.
func restoreSecretReference(name string, data *secretReferenceConversionData, hostNamespace string) *corev1.SecretReference {
	if data == nil {
		return secretReferenceFromName(name, hostNamespace)
	}
	if name == "" && !data.EmptyName {
		return nil
	}
	ref := &corev1.SecretReference{Name: name, Namespace: hostNamespace}
	if data.EmptyNamespace {
		ref.Namespace = ""
	}
	return ref
}

