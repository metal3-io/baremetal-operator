// v1alpha1 is the storage version. v1beta1 is the conversion hub.
//
// The mechanical field-by-field conversion is generated by conversion-gen into
// zz_generated.conversion.go (regenerate with `make generate`). Fields that
// conversion-gen cannot handle are converted by the hand-written
// Convert_* functions in this file.
//
// Following the pattern used by cluster-api-provider-metal3, cluster-api and
// cluster-api-provider-openstack, ConvertTo/ConvertFrom additionally use the
// conversion-data annotation (MarshalData/UnmarshalData, defined locally in
// conversion_data.go) to make the round-trip lossless.
//
// ConvertTo stashes the whole v1alpha1 object (without metadata) in the
// annotation of the v1beta1 object, and ConvertFrom stashes the whole v1beta1
// object in the annotation of the v1alpha1 object, so that the information
// that cannot be represented in the other version is preserved.

// --- BareMetalHost ---

// ConvertTo converts this BareMetalHost (v1alpha1) to the Hub version (v1beta1).
func (src *BareMetalHost) ConvertTo(dstRaw conversion.Hub) error {
	dst := dstRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1alpha1_BareMetalHost_To_v1beta1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}

	// Operate on a copy of the annotations so that we do not modify the input data.
	dst.SetAnnotations(maps.Clone(src.GetAnnotations()))

	// Placeholder for processing the conversion-data annotation which holds
	// data that cannot be represented in v1alpha1, but was present in the
	// v1beta1 object.
	// restored := &BareMetalHost{}
	// hasRestored, err := UnmarshalData(dst, restored)
	// if err != nil {
	// 	return err
	// }
	// if hasRestored {
	// 	// Process the restored data as needed.
	// }

	// Stash the v1alpha1 object so that ConvertFrom can restore what v1beta1
	// cannot represent, including Spec/Status.HardwareProfile and
	// Status.HardwareDetails, which have no peer in v1beta1.
	return MarshalData(src, dst)
}

// ConvertFrom converts the Hub version (v1beta1) to this BareMetalHost (v1alpha1).
func (dst *BareMetalHost) ConvertFrom(srcRaw conversion.Hub) error {
	src := srcRaw.(*metal3apiv1beta1.BareMetalHost)
	if err := Convert_v1beta1_BareMetalHost_To_v1alpha1_BareMetalHost(src, dst, nil); err != nil {
		return err
	}

	// Operate on a copy of the annotations so that we do not modify the input data.
	dst.SetAnnotations(maps.Clone(src.GetAnnotations()))
	restored := &BareMetalHost{}
	hasRestored, err := UnmarshalData(dst, restored)
	if err != nil {
		return err
	}

	// Restore MD5 checksums and the firmware configuration.
	if hasRestored {
		restoreMD5Checksums(restored, dst)
		restoreFirmware(restored, dst)

		// Hardware profiles do not exist in v1beta1, so the names cannot be
		// reconstructed from the hub object.
		dst.Spec.HardwareProfile = restored.Spec.HardwareProfile
		dst.Status.HardwareProfile = restored.Status.HardwareProfile

		// The hardware details are published through the HardwareData
		// resource from v1beta1 on, but the v1alpha1 status still has its own
		// copy and the controller still reads it, so put it back.
		dst.Status.HardwareDetails = restored.Status.HardwareDetails

		// Only the stashed consumer reference has the API version of the
		// consumer, so restore it unless the consumer was changed through
		// v1beta1.
		if sameConsumer(restored.Spec.ConsumerRef, src.Spec.ConsumerRef) {
			dst.Spec.ConsumerRef = restored.Spec.ConsumerRef
		}
	} else {
		// Without stashed data the object did not come from a v1alpha1 one,
		// so it was created through v1beta1, where hardware profiles do not
		// exist. Use the empty profile: otherwise the controller picks
		// "unknown" (or "libvirt") and applies its root device hints to a
		// host whose owner never asked for them.
		dst.Spec.HardwareProfile = EmptyHardwareProfile
	}

	// Restore the Secret references.
	dst.Spec.UserData = restoreSecretReference(
		src.Spec.UserDataName, restored.Spec.UserData, hasRestored, src.Namespace)
	dst.Spec.NetworkData = restoreSecretReference(
		src.Spec.NetworkDataName, restored.Spec.NetworkData, hasRestored, src.Namespace)
	dst.Spec.MetaData = restoreSecretReference(
		src.Spec.MetaDataName, restored.Spec.MetaData, hasRestored, src.Namespace)

	// Stash the v1beta1 object so that ConvertTo can restore what v1alpha1
	// cannot represent.
	return MarshalData(src, dst)
}

// Convert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec converts
// the BareMetalHostSpec to v1beta1, where the online field is renamed to
// poweredOn. Spec.HardwareProfile has no peer at all, so ConvertTo preserves
// it in the conversion-data annotation instead.
func Convert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec(in *BareMetalHostSpec, out *metal3apiv1beta1.BareMetalHostSpec, s apiconversion.Scope) error {
	if err := autoConvert_v1alpha1_BareMetalHostSpec_To_v1beta1_BareMetalHostSpec(in, out, s); err != nil {
		return err
	}

	out.PoweredOn = in.Online

	// The userData, networkData and metaData Secret references are replaced by
	// their names in v1beta1. The namespace is dropped since v1beta1 always uses
	// the namespace of the BareMetalHost.
	out.UserDataName = secretReferenceName(in.UserData)
	out.NetworkDataName = secretReferenceName(in.NetworkData)
	out.MetaDataName = secretReferenceName(in.MetaData)

	return nil
}

// Convert_v1beta1_BareMetalHostSpec_To_v1alpha1_BareMetalHostSpec converts
// the BareMetalHostSpec from v1beta1.
func Convert_v1beta1_BareMetalHostSpec_To_v1alpha1_BareMetalHostSpec(in *metal3apiv1beta1.BareMetalHostSpec, out *BareMetalHostSpec, s apiconversion.Scope) error {
	if err := autoConvert_v1beta1_BareMetalHostSpec_To_v1alpha1_BareMetalHostSpec(in, out, s); err != nil {
		return err
	}

	out.Online = in.PoweredOn

	// The userDataName, networkDataName and metaDataName fields are converted to
	// Secret references with only the name set. The spec does not know the
	// namespace of the BareMetalHost, so BareMetalHost.ConvertFrom fills it in.
	out.UserData = secretReferenceFromName(in.UserDataName, "")
	out.NetworkData = secretReferenceFromName(in.NetworkDataName, "")
	out.MetaData = secretReferenceFromName(in.MetaDataName, "")

	return nil
}

// Convert_v1alpha1_Image_To_v1beta1_Image converts an Image to v1beta1. The
// "md5" checksum type does not exist in v1beta1 and is unset, which lets
// Ironic detect the algorithm from the checksum (same as "auto").
func Convert_v1alpha1_Image_To_v1beta1_Image(in *Image, out *metal3apiv1beta1.Image, s apiconversion.Scope) error {
	if err := autoConvert_v1alpha1_Image_To_v1beta1_Image(in, out, s); err != nil {
		return err
	}
	if in.ChecksumType == MD5 {
		out.ChecksumType = ""
	}
	return nil
}

// restoreMD5Checksums restores the "md5" checksum type recorded in stash on the
// images of dst, as long as the image is unchanged and its type is still unset.
// Otherwise a new checksum, e.g. a SHA256 one, would wrongly be labelled md5.
func restoreMD5Checksums(stash *BareMetalHost, dst *BareMetalHost) {
	restore := func(stashed, image *Image) {
		if stashed == nil || stashed.ChecksumType != MD5 || image == nil {
			return
		}
		if image.ChecksumType == "" && image.URL == stashed.URL && image.Checksum == stashed.Checksum {
			image.ChecksumType = MD5
		}
	}
	restore(stash.Spec.Image, dst.Spec.Image)
	restore(stash.Status.LastAttemptedImage, dst.Status.LastAttemptedImage)
	restore(&stash.Status.Provisioning.Image, &dst.Status.Provisioning.Image)
}

// --- ConsumerRef ---

// The consumer reference is a corev1.ObjectReference in v1alpha1 and a
// ConsumerReference in v1beta1. The latter has the API group of the consumer
// instead of its API version, and no uid, resourceVersion and fieldPath.
//
// v1beta1 does not know the API version of the consumer, so a reference set
// through v1beta1 is converted to the API version "<group>/", from which the
// readers of the v1alpha1 reference still get the right group.
// BareMetalHost.ConvertFrom restores the original reference from the
// conversion-data annotation as long as it points to the same consumer.

// Convert_v1_ObjectReference_To_v1beta1_ConsumerReference converts the
// consumer reference to the hub version.
func Convert_v1_ObjectReference_To_v1beta1_ConsumerReference(in *corev1.ObjectReference, out *metal3apiv1beta1.ConsumerReference, _ apiconversion.Scope) error {
	*out = metal3apiv1beta1.ConsumerReference{
		Name:      in.Name,
		Namespace: in.Namespace,
		APIGroup:  consumerAPIGroup(in.APIVersion),
		Kind:      in.Kind,
	}
	return nil
}

// Convert_v1beta1_ConsumerReference_To_v1_ObjectReference converts the
// consumer reference from the hub version.
func Convert_v1beta1_ConsumerReference_To_v1_ObjectReference(in *metal3apiv1beta1.ConsumerReference, out *corev1.ObjectReference, _ apiconversion.Scope) error {
	*out = corev1.ObjectReference{
		Kind:      in.Kind,
		Namespace: in.Namespace,
		Name:      in.Name,
	}
	if in.APIGroup != "" {
		out.APIVersion = in.APIGroup + "/"
	}
	return nil
}

// consumerAPIGroup returns the API group of an API version, which is empty
// for the core group and for an empty API version.
//
// The group is everything up to the last slash. This is the same as
// schema.ParseGroupVersion for a well-formed API version, but never fails,
// since v1alpha1 does not validate the API version.
func consumerAPIGroup(apiVersion string) string {
	i := strings.LastIndex(apiVersion, "/")
	if i < 0 {
		return ""
	}
	return apiVersion[:i]
}

// sameConsumer reports whether the v1alpha1 reference points to the same
// consumer as the v1beta1 one.
func sameConsumer(ref *corev1.ObjectReference, consumer *metal3apiv1beta1.ConsumerReference) bool {
	if ref == nil || consumer == nil {
		return false
	}
	return ref.Name == consumer.Name &&
		ref.Namespace == consumer.Namespace &&
		ref.Kind == consumer.Kind &&
		consumerAPIGroup(ref.APIVersion) == consumer.APIGroup
}

// --- Firmware ---

// The deprecated firmware configuration (spec.firmware and
// status.provisioning.firmware) is not implemented by any driver and was
// removed from v1beta1. It is dropped when converting to v1beta1 and restored
// from the stashed v1alpha1 object when converting back. Since v1beta1 cannot
// change it, the stashed value is always restored as-is.

// Convert_v1alpha1_ProvisionStatus_To_v1beta1_ProvisionStatus converts the
// ProvisionStatus to v1beta1, dropping the applied firmware configuration.
func Convert_v1alpha1_ProvisionStatus_To_v1beta1_ProvisionStatus(in *ProvisionStatus, out *metal3apiv1beta1.ProvisionStatus, s apiconversion.Scope) error {
	return autoConvert_v1alpha1_ProvisionStatus_To_v1beta1_ProvisionStatus(in, out, s)
}

// restoreFirmware restores the firmware configuration recorded in stash on dst.
func restoreFirmware(stash *BareMetalHost, dst *BareMetalHost) {
	dst.Spec.Firmware = stash.Spec.Firmware
	dst.Status.Provisioning.Firmware = stash.Status.Provisioning.Firmware
}

// --- RootDeviceHints ---

// Three hints were renamed in v1beta1: DeviceName became DevicePath, because it
// may also be a by-path link rather than a device name, and Model and Vendor
// became ModelContains and VendorContains, because they match a substring of
// the actual value rather than all of it. The values themselves do not change,
// so the conversion is lossless in both directions and conversion-gen only
// needs help matching the fields up.

// Convert_v1alpha1_RootDeviceHints_To_v1beta1_RootDeviceHints converts the root
// device hints to the hub version, mapping the renamed fields.
func Convert_v1alpha1_RootDeviceHints_To_v1beta1_RootDeviceHints(in *RootDeviceHints, out *metal3apiv1beta1.RootDeviceHints, s apiconversion.Scope) error {
	if err := autoConvert_v1alpha1_RootDeviceHints_To_v1beta1_RootDeviceHints(in, out, s); err != nil {
		return err
	}

	out.DevicePath = in.DeviceName
	out.ModelContains = in.Model
	out.VendorContains = in.Vendor

	return nil
}

// Convert_v1beta1_RootDeviceHints_To_v1alpha1_RootDeviceHints converts the root
// device hints from the hub version, mapping the renamed fields back.
func Convert_v1beta1_RootDeviceHints_To_v1alpha1_RootDeviceHints(in *metal3apiv1beta1.RootDeviceHints, out *RootDeviceHints, s apiconversion.Scope) error {
	if err := autoConvert_v1beta1_RootDeviceHints_To_v1alpha1_RootDeviceHints(in, out, s); err != nil {
		return err
	}

	out.DeviceName = in.DevicePath
	out.Model = in.ModelContains
	out.Vendor = in.VendorContains

	return nil
}

